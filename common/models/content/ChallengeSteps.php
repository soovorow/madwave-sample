<?php

namespace common\models\content;

use Yii;
use yii\behaviors\TimestampBehavior;
use yii\db\ActiveRecord;
use yii\db\Migration;
use yii\db\Schema;
use yii\helpers\Html;
use yii\web\UploadedFile;

/**
 * @author Dmitry Suvorov <soovorow@gmail.com>
 */
class ChallengeSteps extends ActiveRecord
{
    public $icon_file;

    /**
     * @inheritdoc
     */
    public static function tableName()
    {
        $table_name = 'challenge_steps';

        if (\Yii::$app->db->schema->getTableSchema($table_name) === null) {
            $migration = new Migration();
            $migration->createTable($table_name, [
                'id' => Schema::TYPE_PK,
                'title' => Schema::TYPE_TEXT,
                'date_from' => Schema::TYPE_TEXT,
                'date_to' => Schema::TYPE_TEXT,
                'icon' => Schema::TYPE_TEXT,
                'status' => Schema::TYPE_INTEGER,
                'created_at' => Schema::TYPE_INTEGER,
                'updated_at' => Schema::TYPE_INTEGER,
            ]);
        }

        return $table_name;
    }

    /**
     * @inheritdoc
     */
    public function behaviors()
    {
        return [
            TimestampBehavior::className(),
        ];
    }

    /**
     * @inheritdoc
     */
    public function rules()
    {
        return [
            [
                [
                    'title',
                    'date_from',
                    'date_to',
                    'icon',
                    'status',
                ],
                'default'
            ]
        ];
    }

    public function beforeSave($insert)
    {
        $this->icon_file = UploadedFile::getInstance($this, 'icon_file');
        if ($this->icon_file) {
            $dir = \Yii::getAlias('@frontend/web/images/challenge');
            if (!file_exists($dir)) {
                mkdir($dir, 0777, true);
            }
            exec('chmod 777 '.$dir);
            $path = 'images/challenge/' . md5($this->icon_file->baseName) . '.' . $this->icon_file->extension;
            $this->icon_file->saveAs(\Yii::getAlias('@common/../frontend/web/').$path);
            $this->icon = $path;
        }

        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    public function getIconSrc()
    {
        return Yii::$app->params['baseUrl'].'/'.$this->icon;
    }

    public function getDateRangeString()
    {

        $date_to = explode('.', $this->date_to);
        $dateTo = ['d' => $date_to[0], 'm' => $date_to[1], 'y' => $date_to[2]];

        $date_from = explode('.', $this->date_from);
        $dateFrom = ['d' => $date_from[0], 'm' => $date_from[1], 'y' => $date_from[2]];


        if ($dateTo['y'] == $dateFrom['y']) {
            $year = $dateTo['y'];
        }

        if ($dateTo['m'] == $dateFrom['m']) {
            $month = $dateTo['m'];
        }

        if ($dateTo['d'] == $dateFrom['d']) {
            $day = $dateTo['d'];
        }

        if (isset($year, $month)) {
            $monthYear = $this->getMonthLabel($month).' '.$year;
            if (isset($day)) {
                $dayString = $day;
            } else {
                $dayString = $dateFrom['d'] .' - '. $dateTo['d'];
            }
            return $dayString. ' ' .$monthYear;
        }

        return 'ERROR DATE';

    }

    private function getMonthLabel($m)
    {
        $m = (int) $m;
        switch ($m) {
            case 1:
                $label = 'Января'; break;
            case 2:
                $label = 'Февраля'; break;
            case 3:
                $label = 'Марта'; break;
            case 4:
                $label = 'Апреля'; break;
            case 5:
                $label = 'Мая'; break;
            case 6:
                $label = 'Июня'; break;
            case 7:
                $label = 'Июля'; break;
            case 8:
                $label = 'Августа'; break;
            case 9:
                $label = 'Сентября'; break;
            case 10:
                $label = 'Октября'; break;
            case 11:
                $label = 'Ноября'; break;
            case 12:
                $label = 'Декабря'; break;
            default:
                $label = 'ERROR: Wrong month number;';
        }
        return $label;
    }

    public function getColumns() {
        return [
            'id',
            [
                'attribute' => 'icon',
                'format' => 'raw',
                'value' => function($model) {
                    return Html::img($model->getIconSrc());
                }
            ],
            'title',
            'date_from',
            'date_to',
            [
                'attribute' => 'status',
                'format' => 'raw',
                'value' => function($model) {
                    return $model->status == 0 ? 'Черновик' : 'Опубликовано';
                }
            ],
            [
                'format' => 'raw',
                'value' => function($model) {
                    return
                        Html::a('update', ['update', 'id' => $model->id])
                        .' '. Html::a('delete', ['delete', 'id' => $model->id]);
                }
            ]
        ];
    }

    public function formAttributes() {
        return [
            'status' => [
                'type' => 'dropdown',
                'items' => [
                    0 => 'Черновик',
                    1 => 'Опубликовано'
                ],
            ],
            'icon_file' => ['type' => 'fileInput'],
            'title' => ['type' => 'textInput'],
            'date_from' => ['type' => 'textInput'],
            'date_to' => ['type' => 'textInput'],
        ];
    }



}

