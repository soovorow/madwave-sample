    public static function enableDiscounts()
    {
        Product::getDb()
            ->createCommand()
            ->update(
                Product::tableName(),
                ['discount_card_percent' => 25],
                'discount_card_percent = '.'15'
            )
            ->execute();

        foreach (self::specialDiscounts() as $sku => $percent) {
            if ($v = ProductVariant::findOne($sku)) {
                $v->product->updateAttributes(['discount_card_percent' => $percent]);
            };
        }
    }

    public static function disableDiscounts()
    {
        Product::getDb()
            ->createCommand()
            ->update(
                Product::tableName(),
                ['discount_card_percent' => 10],
                'discount_card_percent = '.'25'
            )
            ->execute();

        foreach (self::defaultDiscounts() as $sku => $percent) {
            if ($v = ProductVariant::findOne($sku)) {
                $v->product->updateAttributes(['discount_card_percent' => $percent]);
            };
        }
    }

