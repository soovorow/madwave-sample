<?php

namespace common\models;

use common\components\MailChimp;
use yii\db\ActiveRecord;
use yii\db\cubrid\Schema;
use yii\db\Migration;

/**
 * Availability Subscribers model
 *
 * Store many-to-many relation between subscriber's emails and product variant ids
 *
 * @author Dmitry Suvorov <soovorow@gmail.com>
 */
class AvailabilitySubscriber extends ActiveRecord
{
    /**
     * @inheritdoc
     */
    public static function tableName()
    {

        $table_name = 'availability_subscriber';

        if (\Yii::$app->db->schema->getTableSchema($table_name) === null) {
            $migration = new Migration();
            $migration->createTable($table_name, [
                'id' => Schema::TYPE_PK,
                'email' => Schema::TYPE_STRING,
                'sku' => Schema::TYPE_STRING
            ]);
        }

        return $table_name;
    }

    /**
     * @inheritdoc
     */
    public function beforeSave($insert)
    {
        (new MailChimp())->addListMember($this->email);
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    /**
     * @inheritdoc
     */
    public function rules()
    {
        return [
            ['email', 'email']
        ];
    }
}