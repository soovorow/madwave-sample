<?php

namespace common\models\content;

use common\components\multilocal\Local;
use Yii;
use yii\db\ActiveRecord;
use yii\db\Migration;
use yii\db\Schema;
use yii\helpers\Html;
use yii\web\UploadedFile;

/**
 * Homepage banner model
 *
 * @property mixed small_title
 * @property mixed small_title_en
 * @property mixed title
 * @property mixed title_en
 * @property mixed text
 * @property mixed text_en
 * @property mixed style
 * @property mixed linkhh
 * @property mixed background
 * @property mixed link
 * @property mixed link_eu
 *
 * @author Dmitry Suvorov <soovorow@gmail.com>
 */
class HomepageBanner extends ActiveRecord
{
    const STATUS_POSTED = 1;

    public $background_file;
    public $icon_file;

    /**
     * @inheritdoc
     */
    public static function tableName()
    {
        $table_name = 'homepage_banners';

        if (\Yii::$app->db->schema->getTableSchema($table_name) === null) {
            $migration = new Migration();
            $migration->createTable($table_name, [
                'id' => Schema::TYPE_PK,
                'background' => Schema::TYPE_TEXT,
                'small_title' => Schema::TYPE_TEXT,
                'small_title_en' => Schema::TYPE_TEXT,
                'title' => Schema::TYPE_TEXT,
                'title_en' => Schema::TYPE_TEXT,
                'text' => Schema::TYPE_TEXT,
                'text_en' => Schema::TYPE_TEXT,
                'link' => Schema::TYPE_TEXT,
                'link_eu' => Schema::TYPE_TEXT,
                'style' => Schema::TYPE_TEXT,
                'status' => Schema::TYPE_INTEGER,
                'enable_ru' => Schema::TYPE_INTEGER,
                'enable_eu' => Schema::TYPE_INTEGER,
            ]);
        }

        return $table_name;
    }

    /**
     * @inheritdoc
     */
    public function rules()
    {
        return [
            [
                [
                    'small_title',
                    'title',
                    'text',
                    'link',
                ],
                'required'
            ],
            [
                [
                    'text_en',
                    'title_en',
                    'small_title_en',
                    'background',
                    'status',
                    'enable_ru',
                    'enable_eu',
                    'link_eu',
                    'style'
                ],
                'default'
            ],
            [
                [
                    'background_file',
                ],
                'file'
            ]
        ];
    }

    public function beforeSave($insert)
    {
        $this->background_file = UploadedFile::getInstance($this, 'background_file');
        if ($this->background_file) {
            $filename = md5($this->background_file->baseName) . '.' . $this->background_file->extension;
            $path = '/var/www/admin/www/stash.madwave.ru/uploads/'.$filename;
            $this->background_file->saveAs($path);
            $this->background = '/images/uploads/'.$filename;
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    public function getColumns() {
        return [
            'id',
            'title',
            'text',
            [
                'attribute' => 'status',
                'format' => 'raw',
                'value' => function($model) {
                    return $model->status == 0 ? 'Черновик' : 'Опубликовано';
                }
            ],
            [
                'format' => 'raw',
                'value' => function($model) {
                    return
                        Html::a('update', ['update', 'id' => $model->id])
                        .' '. Html::a('delete', ['delete', 'id' => $model->id]);
                }
            ]
        ];
    }

    public function formAttributes() {
        return [
            'status' => [
                'type' => 'dropdown',
                'items' => [
                    0 => 'Черновик',
                    1 => 'Опубликовано'
                ],
            ],
            'background_file' => ['type' => 'fileInput'],
            'small_title' => ['type' => 'textInput'],
            'small_title_en' => ['type' => 'textInput'],
            'title' => ['type' => 'textInput'],
            'title_en' => ['type' => 'textInput'],
            'text' => ['type' => 'textInput'],
            'text_en' => ['type' => 'textInput'],
            'link' => ['type' => 'textInput'],
            'link_eu' => ['type' => 'textInput'],
            'style' => ['type' => 'textInput'],
            'enable_ru' => [
                'type' => 'dropdown',
                'items' => [
                    0 => 'Выключено',
                    1 => 'Включено'
                ],
            ],
            'enable_eu' => [
                'type' => 'dropdown',
                'items' => [
                    0 => 'Выключено',
                    1 => 'Включено'
                ],
            ],
        ];
    }

    public static function widget()
    {
        $banners = HomepageBanner::find()
            ->where(['status' => self::STATUS_POSTED])
            ->andWhere([Local::choose([
                Local::RU => 'enable_ru',
                Local::EU => 'enable_eu'
            ]) => 1])
            ->orderBy('id DESC')
            ->indexBy('id')
            ->all();

        if (count($banners) > 0) {
            $items = [];

            foreach ($banners as $i => $b) {
                /** @var $b HomepageBanner */

                $button = null;

                if ($b->id != 22) {
                    $button = Html::a(Yii::t('app', 'More').' <i class="fa fa-chevron-right"></i>', $b->getLink(), [
                        'class' => 'btn btn-lg btn-danger'
                    ]);
                } else {
                    $b->style = $b->style.'; text-align: center;';
                }

                $content = [
                    Html::tag('h3', $b->getSmallTitle() ),
                    Html::tag('h2', $b->getTitle(), ['class' => 'h1']),
                    Html::tag('p', $b->getText()),
                    $button
                ];

                $container = Html::tag('div', implode($content), ['style' => $b->style, 'class' => 'container']);

                $items[] = Html::tag('div', $container, [
                    'style' => 'background: url(\''.$b->background.'\') center center/cover no-repeat',
                    'class' => 'banner'
                ]);
            }

            return Html::tag('section', implode($items), ['id' => 'main-banner']);
        }

        return null;
    }

    public function getSmallTitle() {
        return Local::choose([
            Local::RU => $this->small_title,
            Local::EU => $this->small_title_en,
        ]);
    }
    public function getTitle() {
        return Local::choose([
            Local::RU => $this->title,
            Local::EU => $this->title_en,
        ]);
    }
    public function getText() {
        return Local::choose([
            Local::RU => $this->text,
            Local::EU => $this->text_en,
        ]);
    }

    public function getLink()
    {
        return Local::choose([
            Local::RU => $this->link,
            Local::EU => $this->link_eu,
        ]);
    }
}

