                'icon' => Schema::TYPE_TEXT,
                'small_title' => Schema::TYPE_TEXT,
                'small_title_en' => Schema::TYPE_TEXT,
                'title' => Schema::TYPE_TEXT,
                'title_en' => Schema::TYPE_TEXT,
                'text' => Schema::TYPE_TEXT,
                'text_en' => Schema::TYPE_TEXT,
                'link' => Schema::TYPE_TEXT,
                'link_eu' => Schema::TYPE_TEXT,
                'status' => Schema::TYPE_INTEGER,
            ]);
        }

        if (!isset($table->columns['pos'])) {
            $migration = new Migration;
            $migration->addColumn($table_name, 'pos', $migration->integer()->after('id'));

            /**
             * @var PinnedItems $item
             */
