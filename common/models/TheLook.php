<?php

namespace common\models;

use common\components\multilocal\Local;
use Yii;
use yii\behaviors\SluggableBehavior;
use yii\behaviors\TimestampBehavior;
use yii\db\ActiveRecord;
use yii\db\Migration;
use yii\helpers\Json;
use yii\imagine\Image;
use yii\web\UploadedFile;

/**
 * Collection model
 *
 * @property integer $id
 *
 * @property mixed title
 * @property mixed description
 * @property mixed meta_title
 * @property mixed meta_description
 *
 * @property integer $status
 * @property integer $created_at
 * @property integer $updated_at
 * @property mixed slug
 * @property mixed title_eu
 * @property mixed description_eu
 * @property mixed weight
 *
 * @author Dmitry Suvorov <soovorow@gmail.com>
 */
class TheLook extends ActiveRecord
{
    public $sku_input;
    public $sku_pos;
    public $img;

    /**
     * @inheritdoc
     */
    public static function tableName()
    {

        $table_name = 'the_looks';

        if (\Yii::$app->db->schema->getTableSchema($table_name) === null) {
            $migration = new Migration();
            $migration->createTable($table_name, [
                'id' => $migration->primaryKey(),
                'weight' => $migration->integer(),
                'slug' => $migration->string(),
                'slug_eu' => $migration->string(),
                'image' => $migration->string(),
                'title' => $migration->string(),
                'title_eu' => $migration->string(),
                'description' => $migration->string(),
                'description_eu' => $migration->string(),
                'meta_title' => $migration->string(),
                'meta_title_eu' => $migration->string(),
                'meta_description' => $migration->string(),
                'meta_description_eu' => $migration->string(),

                'status' => $migration->integer(),
                'created_at' => $migration->integer(),
                'updated_at' => $migration->integer(),
            ]);
        }

        return $table_name;
    }

    public function getTitle()
    {
        return Local::choose([
            Local::RU => $this->title,
            Local::EU => $this->title_eu
        ]);
    }


    public function getDescription()
    {
        return Local::choose([
            Local::RU => $this->description,
            Local::EU => $this->description_eu
        ]);
    }

    /**
     * @inheritdoc
     */
    public function behaviors()
    {
        return [
            TimestampBehavior::className(),
            [
                'class' => SluggableBehavior::className(),
                'attribute' => 'title',
                'slugAttribute' => 'slug',
            ],
            [
                'class' => SluggableBehavior::className(),
                'attribute' => 'title_eu',
                'slugAttribute' => 'slug_eu',
            ]
        ];
    }

    public function beforeSave($insert)
    {
        if ($this->isNewRecord) {
            $this->weight = TheLook::find()->max('id') + 1;
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    /**
     * @inheritdoc
     */
    public function rules()
    {
        return [
            ['slug','default'],
            ['slug_eu','default'],
            ['weight','default'],
            ['status','default'],
            ['title','required'],
            ['title_eu','required'],
            ['description','required'],
            ['description_eu','required'],
            ['meta_title','required'],
            ['meta_title_eu','required'],
            ['meta_description','required'],
            ['meta_description_eu','required'],
            ['sku_input','default'],
            ['sku_pos','default'],
            [['image'], 'file', 'skipOnEmpty' => true, 'extensions' => 'png, jpg'],
        ];
    }

    public function uploadImage()
    {

        $this->img = UploadedFile::getInstance($this, 'img');
        if ($this->img) {
            $file = 'uploads/' . md5($this->img->baseName.time()) . '.' . $this->img->extension;
            $rout = \Yii::getAlias('@stash') . '/' . $file;
            $this->img->saveAs($rout);
            $this->image = Json::encode($file);
            return $file;
        }
    }

    public function getImage()
    {
        return Yii::$app->params['baseUrl'].'/images/'.Json::decode($this->image);
    }

    public function setSku($input)
    {
        TheLookItem::deleteAll(['the_look_id' => $this->id]);
        if (!empty($input)) {
            foreach ($input as $variant_id => $bool) {
                if ($bool) {
                    $link = new TheLookItem();
                    $link->the_look_id = $this->id;
                    $link->sku = $variant_id;
                    $link->pos = $this->sku_pos[$variant_id];
                    $link->save(false);
                }
            }
        }
        return $this;
    }

    public function getSku()
    {
        return $this->hasMany(TheLookItem::className(), ['the_look_id' => 'id']);
    }

    public function getVariants($ordered = false)
    {
        if ($ordered) {
            $vars = [];
            foreach ($this->getSku()->orderBy('pos')->all() as $sku) {
                $vars[] = ProductVariant::find()->where(['variant_id' => $sku['sku']])->one();
            }
            return $vars;
        } else {
            return $this->hasMany(ProductVariant::className(), ['variant_id' => 'sku'])
                ->via('sku');
        }
    }
}