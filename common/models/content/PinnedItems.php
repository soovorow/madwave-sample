    /**
     * @inheritdoc
     */
    public function rules()
    {
        return [
            [
                [
                    'small_title',
                    'title',
                    'text',
                    'link',
                ],
                'required'
            ],
            [['pos'], 'number'],
            [
                [
                    'small_title_en',
                    'title_en',
                    'text_en',
                    'background',
                    'icon',
                    'link_eu',
                    'status',
                ],
                'default'
            ],
            [
                [
                    'background_file',
                    'icon_file',
                ],
                'file'
            ]
        ];
    }

    public function beforeSave($insert)
    {
        $this->background_file = UploadedFile::getInstance($this, 'background_file');
        if ($this->background_file) {
            $filename = md5($this->background_file->baseName) . '.' . $this->background_file->extension;
            $path = '/var/www/admin/www/stash.madwave.ru/uploads/'.$filename;
            $this->background_file->saveAs($path);
            $this->background = '/images/uploads/'.$filename;
        }

        $this->icon_file = UploadedFile::getInstance($this, 'icon_file');
        if ($this->icon_file) {
            $filename = md5($this->icon_file->baseName) . '.' . $this->icon_file->extension;
            $path = '/var/www/admin/www/stash.madwave.ru/uploads/'.$filename;
            $this->icon_file->saveAs($path);
            $this->icon = '/images/uploads/'.$filename;
        }

        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    public function getColumns() {
        return [
            'id',
            'title',
            'text',
            'pos',
            [
                'attribute' => 'status',
                'format' => 'raw',
                'value' => function($model) {
                    return $model->status == 0 ? 'Черновик' : 'Опубликовано';
                }
            ],
            [
                'format' => 'raw',
                'value' => function($model) {
                    return
                        Html::a('update', ['update', 'id' => $model->id]).' '.
                        Html::a('delete', ['delete', 'id' => $model->id]).' '.
                        Html::a('up', ['move-up', 'id' => $model->id]).' '.
                        Html::a('down', ['move-down', 'id' => $model->id]);
                }
            ]
        ];
    }

    public function formAttributes() {
        return [
            'status' => [
                'type' => 'dropdown',
                'items' => [
                    0 => 'Черновик',
                    1 => 'Опубликовано'
                ],
            ],
            'background_file' => ['type' => 'fileInput'],
            'dbf' => [
                'type' => 'action',
                'name' => 'delete background',
                'url' => ['/pinned-items/delete-background', 'id' => $this->id]
            ],
            'icon_file' => ['type' => 'fileInput'],
            'dif' => [
                'type' => 'action',
                'name' => 'delete icon',
                'url' => ['/pinned-items/delete-icon', 'id' => $this->id]
            ],
            'small_title' => ['type' => 'textInput'],
            'small_title_en' => ['type' => 'textInput'],
            'title' => ['type' => 'textInput'],
            'title_en' => ['type' => 'textInput'],
            'text' => ['type' => 'textInput'],
            'text_en' => ['type' => 'textInput'],
            'link' => ['type' => 'textInput'],
            'link_eu' => ['type' => 'textInput'],
        ];
    }

    public function getTitle() {
        return Local::choose([
            Local::RU => $this->title,
            Local::EU => $this->title_en
        ]);
    }

    public function getSmallTitle() {
        return Local::choose([
            Local::RU => $this->small_title,
            Local::EU => $this->small_title_en
        ]);
    }

    public function getText() {
        return Local::choose([
            Local::RU => $this->text,
            Local::EU => $this->text_en
        ]);
    }

    public function getLink() {
        return Local::choose([
            Local::RU => $this->link,
            Local::EU => $this->link_eu
        ]);
    }

    public static function widget()
    {
        $items = PinnedItems::find()->where(['status'=>1])->orderBy('pos')->all();

        if (count($items) > 0) {

            $content = [];

            foreach ($items as $item) {

                /** @var $item PinnedItems */

                $small = Html::tag('small', $item->getSmallTitle());
                $icon = Html::tag('div', null, [
                    'style' => 'background: url(\''.$item->icon.'\') center center / contain no-repeat'
                ]);

                $data = [
                    Html::tag('div', $icon, [
                        'class' => 'background',
                        'style' => 'background: url(\''.$item->background.'\') center center / cover'
                    ]),
                    Html::tag('h4', $small.$item->getTitle()),
                    Html::tag('p', $item->getText()),
                    Html::a(Yii::t('app', 'More'), $item->getLink(), ['class' => 'btn btn-lg btn-default'])
                ];

                $i = Html::tag('div', implode($data), ['class' => 'pinned-item']);

                $content[] = Html::tag('div', $i, ['class' => 'col-sm-4']);
            }

            $container = Html::tag('div', implode($content), ['class' => 'container p0']);
            return Html::tag('section', $container, ['id' => 'pinned-items']);
        }
    }


}

